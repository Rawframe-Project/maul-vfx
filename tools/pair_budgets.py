# Derives rhi_pairs' bounds on the rigid bodies that go apart, and writes
# them into test/rhi_pair_budgets.h.
#
# Bodies meeting each other are chaotic. In test_rhi_pairs, a binary32
# unit's difference between the paths parts some bodies however exact the
# kernels are. So a scene's bound is not a correctness count. It bounds
# that divergence, measured: the suite runs once as it is and once for each
# perturbation k, the CPU path's adopted places moved by k 2^-20 of
# themselves (MVFX_RHI_PERTURB, rhi_harness.c). Each scene's bound is the
# most any run parted, times FACTOR, plus SLACK.
#
# The margin is how far past the ensemble's largest count a new run may
# go. In the ensemble the header holds, no scene's largest count is more
# than 1.57 times its next largest (the pool's contacts dropped: 58 against
# 37; the others 1.5 or less, the counts ranging from 7 to 58 by k), and
# no small count is more than 2 above its next (6 against 4). Times 1.5
# plus 4 lets a new perturbation step past the largest as far again as the
# widest step the ensemble shows, by its ratio for a large count and by a
# few bodies for a small one. A run that still exceeds a bound calls for
# more runs or a wider margin here, not an edit of the header.
#
# Run it again whenever the kernels' or the core's arithmetic changes, on a
# machine with lavapipe, through the shared machine's heavy-job limiter:
#
#   cmake --preset linux-rhi-lavapipe && cmake --build --preset linux-rhi-lavapipe
#   python3 tools/pair_budgets.py --write
#
# Without --write it prints the counts and the bounds they give. With
# --rewrite it runs nothing and writes the header again from the counts it
# holds, after a change to the margin or to this script's text.
#
# usage: pair_budgets.py [--preset PRESET] [--perturb K ...] [--write | --rewrite]

import argparse
import math
import os
import re
import subprocess
import sys
import textwrap

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(ROOT, "test", "rhi_pair_budgets.h")
FACTOR = 1.5
SLACK = 4

SCENE = re.compile(r"^(?:\d+: )?(.+?): largest relative differences")
APART = re.compile(r"^(?:\d+: )?\s+particles apart: (\d+) \(at most -?\d+\)$")
FAIL = re.compile(r"^(?:\d+: )?FAIL: (.+?) \(")


def run(preset, k):
    """Each scene's bodies apart in one run of rhi_pairs, and the failures
    that are not a bound's."""
    env = dict(os.environ, MVFX_RHI_PERTURB=str(k))
    result = subprocess.run(
        ["ctest", "--preset", preset, "-R", "^rhi_pairs$", "--timeout", "3600", "-V"],
        cwd=ROOT, env=env, capture_output=True, text=True)
    counts = {}
    others = []
    scene = None
    for line in result.stdout.splitlines():
        m = SCENE.match(line)
        if m:
            scene = m.group(1)
            continue
        m = APART.match(line)
        if m and scene is not None:
            counts[scene] = int(m.group(1))
            continue
        m = FAIL.match(line)
        if m and m.group(1) != "particles apart":
            others.append(m.group(1))
    return counts, others


def bound(largest):
    return math.ceil(largest * FACTOR) + SLACK


def write(scenes, runs, perturbations):
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Copyright (c) 2026 Sirac Ozmen",
        "//",
        "// Generated by tools/pair_budgets.py (python3 tools/pair_budgets.py",
        "// --write, on lavapipe): not edited by hand; run the command again.",
    ] + ["// " + line for line in textwrap.wrap(
        "rhi_pairs' bound on the bodies each scene parts: the most parted over runs "
        "with the CPU path's adopted places moved by k 2^-20 of themselves, k = " +
        ", ".join(str(k) for k in perturbations) +
        f", times {FACTOR} plus {SLACK} (the tool says why). A bound on chaotic "
        "divergence under perturbation, not a correctness count. Each scene's counts "
        "by k, in that order, come before it.", 73)] + [
        "",
        "#ifndef MAUL_VFX_TEST_RHI_PAIR_BUDGETS_H",
        "#define MAUL_VFX_TEST_RHI_PAIR_BUDGETS_H",
        "",
        "#include <stdint.h>",
        "",
        "typedef struct PairBudget",
        "{",
        "    const char* scene;",
        "    int32_t mostApart;",
        "} PairBudget;",
        "",
        "static const PairBudget s_pairBudgets[] = {",
    ]
    for scene in scenes:
        counts = [runs[k][scene] for k in perturbations]
        lines.append(f"    // {' '.join(str(c) for c in counts)}")
        lines.append(f'    {{"{scene}", {bound(max(counts))}}},')
    lines += ["};", "", "#endif", ""]
    with open(HEADER, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    subprocess.run(["clang-format", "-i", HEADER], check=True)


def read():
    """The perturbations and each scene's counts the header holds."""
    with open(HEADER, encoding="utf-8") as f:
        text = f.read()
    prose = re.sub(r"\n// ", " ", text)
    perturbations = [int(k) for k in re.search(r"k = ([-\d, ]+?), times", prose).group(1).split(", ")]
    runs = {k: {} for k in perturbations}
    scenes = []
    for m in re.finditer(r'// ([\d ]+)\n\s*\{"(.+?)",', text):
        counts = [int(c) for c in m.group(1).split()]
        scenes.append(m.group(2))
        for k, count in zip(perturbations, counts):
            runs[k][m.group(2)] = count
    return scenes, runs, perturbations


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--preset", default="linux-rhi-lavapipe")
    parser.add_argument("--perturb", type=int, nargs="+", default=[0, 1, -1, 2, -2])
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--rewrite", action="store_true")
    args = parser.parse_args()
    if args.rewrite:
        write(*read())
        return
    runs = {}
    scenes = []
    for k in args.perturb:
        counts, others = run(args.preset, k)
        if others:
            sys.exit(f"k = {k}: failures other than a bound's: {'; '.join(others)}")
        if not counts:
            sys.exit(f"k = {k}: no scene's count in rhi_pairs' output")
        for scene in counts:
            if scene not in scenes:
                scenes.append(scene)
        runs[k] = counts
        print(f"k = {k}: " + ", ".join(f"{counts[s]}" for s in scenes), flush=True)
    missing = [(k, s) for k in args.perturb for s in scenes if s not in runs[k]]
    if missing:
        sys.exit(f"scenes missing from a run: {missing}")
    for scene in scenes:
        counts = [runs[k][scene] for k in args.perturb]
        print(f"{scene}: {counts} -> {bound(max(counts))}")
    if args.write:
        write(scenes, runs, args.perturb)


main()
